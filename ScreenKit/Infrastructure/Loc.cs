namespace ScreenKit;

/// <summary>
/// 界面中英文：zh / en。键用短 id，缺键时回退中文再回退键名。
/// </summary>
static class Loc {
	public const string Zh = "zh";
	public const string En = "en";

	static string lang = Zh;

	public static string Lang {
		get => lang;
		set {
			var v = (value ?? "").Trim().ToLowerInvariant();
			if (v is "en" or "en-us" or "english") lang = En;
			else lang = Zh;
		}
	}

	public static bool IsEn => lang == En;
	public static bool IsZh => lang != En;

	public static string T(string key) {
		if (string.IsNullOrEmpty(key)) return "";
		if (IsEn && EnMap.TryGetValue(key, out var en) && !string.IsNullOrEmpty(en))
			return en;
		if (ZhMap.TryGetValue(key, out var zh) && !string.IsNullOrEmpty(zh))
			return zh;
		return key;
	}

	public static string T(string key, params object[] args) {
		try { return string.Format(T(key), args); }
		catch { return T(key); }
	}

	public static void SetFromConfig(string uiLang) => Lang = uiLang;

	public static string Compute(TtsComputeMode mode) => mode switch {
		TtsComputeMode.Gpu => T("compute.gpu"),
		TtsComputeMode.Igpu => T("compute.igpu"),
		TtsComputeMode.Cpu => T("compute.cpu"),
		_ => T("compute.auto"),
	};

	public static string LangName(string code) {
		code = TrLang.Normalize(code ?? "");
		if (string.IsNullOrEmpty(code)) return T("lang.all");
		if (code == "auto") return T("lang.auto");
		var key = "lang." + code;
		var name = T(key);
		return name == key ? code : name;
	}

